    QVERIFY(outcome.fault.contains(QStringLiteral("不允许访问的内存")));
    QVERIFY(outcome.fault.contains(QStringLiteral("SIGSEGV")));
    QVERIFY(outcome.place.contains(QStringLiteral("main")));
    QVERIFY(outcome.place.contains(QStringLiteral("demo.c:4")));
    QVERIFY(outcome.likely.contains(QStringLiteral("空")));
    QVERIFY(outcome.advice.contains(QStringLiteral("不要删除")));
    QVERIFY(outcome.document.contains(QStringLiteral("分步操作")));
    QVERIFY(outcome.document.contains(QStringLiteral("中文释义")));
    QVERIFY(outcome.document.contains(QStringLiteral("建议解决方案")));
    QVERIFY(outcome.document.contains(QStringLiteral("-b")));
    QVERIFY(outcome.document.contains(QStringLiteral("--notes")));
    QVERIFY(outcome.document.contains(QStringLiteral("--core")));
    QVERIFY(outcome.document.contains(QStringLiteral("thread apply all bt")));
    QVERIFY(outcome.document.contains(path));
    QCOMPARE(QString::fromUtf8(outcome.document.toUtf8()), outcome.document);
    requireShownCommands(outcome, host);

    const tw::ArgvTask *debugger = nullptr;
    for (const tw::ArgvTask &call : host.calls) {
        if (QFileInfo(call.program).fileName() == QStringLiteral("gdb"))
            debugger = &call;
    }
    QVERIFY(debugger);
    QVERIFY(debugger->arguments.contains(path));
    QVERIFY(debugger->arguments.contains(QStringLiteral("/bin/true")));
    const int coreFlag = debugger->arguments.indexOf(QStringLiteral("-c"));
    QVERIFY(coreFlag >= 0);
    QCOMPARE(debugger->arguments.at(coreFlag + 1), path);
