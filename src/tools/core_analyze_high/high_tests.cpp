class ScriptedHost : public tw::ArgvHost
{
public:
    QHash<QString, tw::ArgvResult> byName;
    QVector<tw::ArgvTask> calls;
    int delayMs = 0;
    std::atomic<bool> *stop = nullptr;

    tw::ArgvResult run(const tw::ArgvTask &task) override
    {
        calls.append(task);
        if (delayMs > 0) {
            const int slices = qMax(1, delayMs / 20);
            for (int i = 0; i < slices; ++i) {
                if (stop && stop->load()) {
                    tw::ArgvResult cancelled;
                    cancelled.state = tw::ArgvState::Stopped;
                    cancelled.detail = QStringLiteral("已取消");
                    return cancelled;
                }
                QThread::msleep(20);
            }
        }
        const QString base = QFileInfo(task.program).fileName();
        if (byName.contains(base))
            return byName.value(base);
        tw::ArgvResult missing;
        missing.state = tw::ArgvState::NotFound;
        missing.detail = QStringLiteral("scripted miss");
        return missing;
    }
};

tw::ArgvResult finishedText(const QString &text)
{
    tw::ArgvResult result;
    result.state = tw::ArgvState::Finished;
    result.exitCode = 0;
    result.text = text;
    return result;
}

tw::ToolLocator presentTools()
{
    return [](const QString &name) {
        const QStringList known = {QStringLiteral("file"), QStringLiteral("eu-readelf"),
                                   QStringLiteral("readelf"), QStringLiteral("eu-unstrip"),
                                   QStringLiteral("gdb")};
        if (known.contains(name))
            return QStringLiteral("/usr/bin/") + name;
        return QString();
    };
}

QByteArray elfHeader(int type)
{
    QByteArray header(64, '\0');
    header[0] = 0x7f;
    header[1] = 'E';
    header[2] = 'L';
    header[3] = 'F';
    header[4] = 2;
    header[5] = 1;
    header[6] = 1;
    header[16] = static_cast<char>(type);
    header[18] = 0x3e;
    header[20] = 1;
    return header;
}

QString writeBytes(const QString &path, const QByteArray &bytes)
{
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile file(path);
    file.open(QIODevice::WriteOnly | QIODevice::Truncate);
    file.write(bytes);
    return QFileInfo(path).absoluteFilePath();
}

