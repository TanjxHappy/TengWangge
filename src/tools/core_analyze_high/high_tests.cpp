void HighAnalyzeTests::binutilsReadelfFallbackNamesTheGap()
{
    QTemporaryDir dir;
    QVERIFY(dir.isValid());
    const QString path = writeBytes(dir.filePath(QStringLiteral("demo.core")), elfHeader(4));
    ScriptedHost host;
    host.byName.insert(QStringLiteral("file"), finishedText(kFileOut));
    host.byName.insert(QStringLiteral("readelf"), finishedText(kNotesOut));
    host.byName.insert(QStringLiteral("gdb"), finishedText(kDebuggerOut));
    auto locator = [](const QString &name) {
        if (name == QLatin1String("eu-readelf") || name == QLatin1String("eu-unstrip"))
            return QString();
        if (name == QLatin1String("file") || name == QLatin1String("readelf")
            || name == QLatin1String("gdb")) {
            return QStringLiteral("/usr/bin/") + name;
        }
        return QString();
    };
    tw::TriageInput input;
    input.corePath = path;
    const tw::TriageOutcome outcome = tw::CoreTriage::run(input, host, locator);
    QVERIFY(outcome.accepted);
    QVERIFY(outcome.document.contains(QStringLiteral("没有找到 eu-readelf")));
    QVERIFY(outcome.document.contains(QStringLiteral("已改用 readelf")));
    const tw::ArgvTask *notes = nullptr;
    for (const tw::ArgvTask &call : host.calls) {
        if (QFileInfo(call.program).fileName() == QStringLiteral("readelf"))
            notes = &call;
    }
    QVERIFY(notes);
    QVERIFY(notes->arguments.contains(QStringLiteral("-n")));
    QVERIFY(notes->arguments.contains(QStringLiteral("-W")));
    requireShownCommands(outcome, host);
}

