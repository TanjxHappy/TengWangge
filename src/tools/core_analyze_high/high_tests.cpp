void HighAnalyzeTests::argvIsNotAShell()
{
    QTemporaryDir dir;
    QVERIFY(dir.isValid());
    const QString corePath = writeBytes(dir.filePath(QStringLiteral("core;id")), elfHeader(4));
    const QString symbolDir = dir.filePath(QStringLiteral("sym dir"));
    QVERIFY(QDir().mkpath(symbolDir));
    ScriptedHost host;
    fillCrash(&host);
    tw::TriageInput input;
    input.corePath = corePath;
    input.debugPath = symbolDir;
    const tw::TriageOutcome outcome = tw::CoreTriage::run(input, host, presentTools());
    QVERIFY(outcome.accepted);
    const tw::ArgvTask *debugger = nullptr;
    for (const tw::ArgvTask &call : host.calls) {
        const QString base = QFileInfo(call.program).fileName();
        QVERIFY(base != QStringLiteral("sh"));
        QVERIFY(base != QStringLiteral("bash"));
        QVERIFY(base != QStringLiteral("dash"));
        QVERIFY(!call.arguments.contains(QStringLiteral("sh")));
        if (base == QStringLiteral("gdb"))
            debugger = &call;
        else
            QVERIFY(!call.arguments.contains(QStringLiteral("-c")));
    }
    QVERIFY(debugger);
    const int coreFlag = debugger->arguments.indexOf(QStringLiteral("-c"));
    QVERIFY(coreFlag >= 0);
    QVERIFY(coreFlag + 1 < debugger->arguments.size());
    QCOMPARE(debugger->arguments.at(coreFlag + 1), QFileInfo(corePath).absoluteFilePath());
    int directoryArgs = 0;
    for (const QString &argument : debugger->arguments) {
        if (argument.contains(QStringLiteral("debug-file-directory"))) {
            ++directoryArgs;
            QVERIFY(argument.contains(QFileInfo(symbolDir).absoluteFilePath()));
        }
    }
    QCOMPARE(directoryArgs, 1);
    QVERIFY(outcome.document.contains(QLatin1Char('\'')));
    requireShownCommands(outcome, host);
}

