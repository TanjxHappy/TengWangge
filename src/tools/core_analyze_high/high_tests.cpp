void requireShownCommands(const tw::TriageOutcome &outcome, const ScriptedHost &host)
{
    for (const tw::ArgvTask &call : host.calls) {
        const QString shown = tw::joinArgvForDisplay(call.program, call.arguments);
        QVERIFY2(outcome.document.contains(shown), qPrintable(shown));
    }
}

QString visibilityProblem(QWidget *widget, QWidget *window, int minHeight)
{
    if (!widget)
        return QStringLiteral("控件不存在");
    if (!widget->isVisible())
        return QStringLiteral("%1 不可见").arg(widget->objectName());
    const QRegion region = widget->visibleRegion();
    if (region.isEmpty()) {
        return QStringLiteral("%1 的可见区域为空，尺寸 %2x%3")
            .arg(widget->objectName())
            .arg(widget->width())
            .arg(widget->height());
    }
    const QRect box = region.boundingRect();
    const QPoint origin = widget->mapTo(window, box.topLeft());
    const QRect mapped(origin, box.size());
    if (mapped.width() < 8 || mapped.height() < minHeight) {
        return QStringLiteral("%1 可见区域过小 %2x%3，窗口 %4x%5")
            .arg(widget->objectName())
            .arg(mapped.width())
            .arg(mapped.height())
            .arg(window->width())
            .arg(window->height());
    }
    if (!window->rect().contains(mapped.topLeft()) || mapped.bottom() > window->rect().bottom()
        || mapped.right() > window->rect().right()) {
        return QStringLiteral("%1 可见区域 %2,%3 %4x%5 超出窗口 %6x%7")
            .arg(widget->objectName())
            .arg(mapped.x())
            .arg(mapped.y())
            .arg(mapped.width())
            .arg(mapped.height())
            .arg(window->width())
            .arg(window->height());
    }
    return {};
}

void shot(QWidget *widget, const QString &name)
{
    const QString dir = qEnvironmentVariable("TENGWANGGE_SCREENSHOT_DIR");
    if (dir.isEmpty() || !widget)
        return;
    QApplication::processEvents();
    widget->grab().save(dir + QLatin1Char('/') + name + QStringLiteral(".png"), "PNG");
}

class PageHarness
{
public:
    explicit PageHarness(const QString &root)
        : platform(tw::DataPaths(root))
    {
        tw::ToolContext context;
        context.info = tool.info();
        context.services = platform.servicesFor(tool.info().id);
        QString error;
        initialized = tool.initialize(context, &error);
        initError = error;
        if (!initialized)
            return;
        pages = tool.createPages();
        page = tool.page();
    }

    ~PageHarness()
    {
        tool.shutdown();
        for (const tw::ToolPage &item : pages)
            delete item.widget;
    }

    tw::PlatformServices platform;
    tw::HighAnalyzeTool tool;
    bool initialized = false;
    QString initError;
    QVector<tw::ToolPage> pages;
    tw::HighAnalyzePage *page = nullptr;
};

